/*===========游戏函数=============*/
// 显示分数
void Show_Score(void)
{
    OLED_ShowNum(1, 17, Score, 5, 6);
}

// 绘制滚动地面
void Show_Ground(void)
{
    if(Ground_Pos<128)
    {
        for(uint8_t i=0;i<128;i++)
        {
            OLED_Buffer[7][i]=Ground[i+Ground_Pos];
        }
    }
    else
    {
        for(uint8_t i=0;i<255-Ground_Pos;i++)
        {
            OLED_Buffer[7][i]=Ground[i+Ground_Pos];
        }
        for(uint8_t i=255-Ground_Pos;i<128;i++)
        {
            OLED_Buffer[7][i]=Ground[i-(255-Ground_Pos)];
        }
    }
}

// 绘制障碍物
void Show_Barrier(void)
{
    if(Barrier_Pos >= 143)
    {
        barrier_flag = rand()%3;
    }
    OLED_ShowImage_Reverse(127-Barrier_Pos, 44, 16, 18, Barrier[barrier_flag], 1);

    barrier.minX = (127 - Barrier_Pos) + 5;
    barrier.minY = 44 + 4;
    barrier.maxX = (127 - Barrier_Pos) +11;
    barrier.maxY = 62;
}

// 绘制云朵
void Show_Cloud(void)
{
    OLED_ShowImage(127-Cloud_Pos, 9, 16, 8, Cloud);
}

// 绘制恐龙
void Show_Dino(void)
{
    IsKey=Key_GetNum();
    if(IsKey == 1 && dino_jump_flag == 0)
    {
        dino_jump_flag = 1;
    }

    if (dino_jump_flag) 
    {
        Jump_Pos = 28 * sin((float)(pi * jump_t / 1000));
    } 
    else 
    {
        Jump_Pos = 0;
    }

    // 恐龙的基础Y坐标设置为42
    // 图像高18，42+18=60。地面在Y=56~63，所以恐龙脚部略微踩入地面，视觉上更稳。
    uint8_t dino_base_y = 42; 
    uint8_t current_dino_y = dino_base_y - Jump_Pos;

    // 根据状态绘制不同的恐龙图像
    if(dino_jump_flag==0)
    {
        // 奔跑动画：根据地面移动距离切换两张图片(左右脚交替)
        if((Ground_Pos / 8) % 2 == 0) 
            OLED_ShowImage(0, current_dino_y, 16, 18, Dino[0]);
        else 
            OLED_ShowImage(0, current_dino_y, 16, 18, Dino[1]);
    }
    else
    {
        // 跳跃时的静态图片
        OLED_ShowImage(0, current_dino_y, 16, 18, Dino[2]);
    }
    
    // 更新恐龙的碰撞箱
    // X固定在0，宽度16。为了防误触，X范围缩进到 4~12
    dino.minX = 0 + 4;
    dino.maxX = 16 - 4;
    dino.minY = current_dino_y + 2;
    dino.maxY = current_dino_y + 18 - 2;
}

// 碰撞检测逻辑 (AABB算法)
// 返回值: 1=碰撞, 0=安全
int IsColliding(struct Object_Position *a, struct Object_Position *b)
{
    // 如果两个矩形区域有重叠，则发生碰撞
    if( (a->maxX > b->minX) && 
        (a->minX < b->maxX) && 
        (a->maxY > b->minY) && 
        (a->minY < b->maxY) )
    {
        // 碰撞发生，显示 Game Over
        OLED_Clear();
        OLED_ShowString(2, 4, "GAME  OVER", 8); 
        OLED_Update();
        
        // 停顿1.5秒让玩家看到结果
        HAL_Delay(1500); 
        
        // 清屏准备重新开始
        OLED_Clear();
        OLED_Update();
        return 1;
    }
    return 0;
}


// 游戏主循环
int DinoGame_Animation(void)
{
    while(1)
    {
        int res_flag=0;
        OLED_Clear();

        Show_Ground();
        Show_Cloud();
        Show_Barrier();
        Show_Dino();
        Show_Score();
        OLED_Update();

        res_flag=IsColliding(&dino, &barrier);
        if(res_flag==1)
            return 0;
    }
}

// 游戏逻辑定时器中断调用函数 (通常在1ms定时器中调用)
void Dino_Tick(void)
{
    static uint8_t Score_Count, Ground_Count, Cloud_Count;

    Score_Count++;
    Ground_Count++;
    Cloud_Count++;

    if(Score_Count >= 100)
    {
        Score_Count = 0;
        Score++;
    }

    // 地面和障碍物移动逻辑
    if(Ground_Count >= 20) 
    {
        Ground_Count = 0;
        Ground_Pos++;
        Barrier_Pos++;
        
        if(Ground_Pos >= 256) Ground_Pos = 0;
        if(Barrier_Pos >= 144) Barrier_Pos = 0;
    }

    if(Cloud_Count >= 50)
    {
        Cloud_Count = 0;
        Cloud_Pos++;
        if(Cloud_Pos >= 200) Cloud_Pos = 0;
    }

    if(dino_jump_flag == 1)
    {
        jump_t++;
        if(jump_t >= 1000)
        {
            jump_t = 0;
            dino_jump_flag = 0;
        }
    }
}

// 游戏数据初始化
void DinoGame_Pos_Init(void)
{
    Score = 0;
    Ground_Pos = 0;
    Barrier_Pos = 0;
    Cloud_Pos = 0;
    Jump_Pos = 0;
    dino_jump_flag = 0;
    jump_t = 0;
    // 初始让障碍物归零，避免一开局就生成在脸上
    Barrier_Pos = 0; 
    barrier_flag = 0;
}

